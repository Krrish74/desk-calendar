// copy-icons.js: copies the Fluent UI System Icons the app uses into src/assets/icons/
// and writes src/renderer/icons.css with one CSS class per icon.
//
// Run with:  npm run icons:copy
// To add an icon: find its name at https://github.com/microsoft/fluentui-system-icons
// (e.g. "calendar_add"), add it to ICONS below, re-run, then use <i class="ico i-calendar_add"></i>.
//
// Icons are drawn with CSS masks, so they take the text color (currentColor) of
// whatever they're in. `.i-NAME` is the outline version, `.i-NAME-filled` the filled one.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'node_modules/@fluentui/svg-icons');
const OUT = path.join(ROOT, 'src/assets/icons');
const CSS = path.join(ROOT, 'src/renderer/icons.css');

const ICONS = [
  'navigation', 'chevron_left', 'chevron_right', 'chevron_down', 'arrow_sync', 'pin', 'chat',
  'settings', 'add', 'video', 'location', 'calendar_ltr', 'arrow_left', 'dismiss', 'checkmark',
  'delete', 'edit', 'open', 'copy', 'alert', 'color', 'text_description', 'clock', 'sparkle',
  'send', 'arrow_undo', 'person', 'link', 'task_list_ltr', 'circle', 'checkmark_circle', 'calendar_clock',
];

fs.mkdirSync(OUT, { recursive: true });
let css = `/* GENERATED by scripts/copy-icons.js. Don't edit by hand. Fluent UI System Icons (MIT). */
.ico { display: inline-block; width: 20px; height: 20px; flex-shrink: 0; background: currentColor;
  -webkit-mask: var(--icon) center / contain no-repeat; mask: var(--icon) center / contain no-repeat; }
`;
for (const name of ICONS) {
  for (const style of ['regular', 'filled']) {
    const file = `${name}_20_${style}.svg`;
    const from = path.join(SRC, 'icons', file);
    if (!fs.existsSync(from)) throw new Error(`Icon not found: ${file}`);
    fs.copyFileSync(from, path.join(OUT, file));
    const cls = style === 'regular' ? `i-${name}` : `i-${name}-filled`;
    css += `.${cls} { --icon: url(../assets/icons/${file}); }\n`;
  }
}
