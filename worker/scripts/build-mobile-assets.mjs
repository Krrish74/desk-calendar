// build-mobile-assets.mjs: copies the files the phone app needs into ../mobile.
//
//   node scripts/build-mobile-assets.mjs      (or: npm run assets)
//
// • Fluent UI System Icons (MIT, from the root project's @fluentui/svg-icons package)
//   → mobile/icons/*.svg, plus mobile/css/icons.css with one class per icon:
//     <i class="ico i-sparkle"></i>  (add "-filled" for the filled style)
// • The app icon src/assets/icon.svg → mobile/icon.svg
// • mobile/sw.js: the list of files to save for offline use + a fingerprint (see sw.js)
// (The PNG Home Screen icons are made by make-mobile-icons.cjs: npm run icons.)
// The output is committed. Run it after changing anything in mobile/ (deploy runs it for you).

import { copyFileSync, mkdirSync, writeFileSync, existsSync, readFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const mobile = join(root, 'mobile');
const fluent = join(root, 'node_modules', '@fluentui', 'svg-icons', 'icons');

// ← icons the phone UI uses (24 px versions; each gets a regular and a filled style)
const ICONS = [
  'calendar_agenda', 'calendar_day', 'calendar_3_day', 'calendar_month', 'calendar_today', 'calendar_ltr',
  'sparkle', 'settings', 'add', 'chevron_left', 'chevron_right', 'chevron_down', 'video', 'location',
  'dismiss', 'edit', 'delete', 'open', 'copy', 'alert', 'clock', 'text_description', 'color', 'person',
  'checkmark', 'arrow_undo', 'send', 'sign_out', 'arrow_clockwise', 'link', 'chat', 'history',
  'checkmark_circle', 'circle', 'task_list_ltr', 'calendar_clock',
];

if (!existsSync(fluent)) {
  console.error('Run `npm install` in the project root first (it provides @fluentui/svg-icons).');
  process.exit(1);
}
mkdirSync(join(mobile, 'icons'), { recursive: true });
mkdirSync(join(mobile, 'css'), { recursive: true });

let css = '/* GENERATED by worker/scripts/build-mobile-assets.mjs. Don\'t edit by hand.\n'
  + '   Fluent UI System Icons (MIT): see icons/LICENSE. */\n'
  + '.ico { display: inline-block; width: 24px; height: 24px; flex-shrink: 0; background: currentColor;\n'
  + '  -webkit-mask: var(--icon) center / contain no-repeat; mask: var(--icon) center / contain no-repeat; }\n';
for (const name of ICONS) {
  for (const style of ['regular', 'filled']) {
    const file = `${name}_24_${style}.svg`;
    copyFileSync(join(fluent, file), join(mobile, 'icons', file));
  }
  css += `.i-${name} { --icon: url(../icons/${name}_24_regular.svg); }\n`;
  css += `.i-${name}-filled { --icon: url(../icons/${name}_24_filled.svg); }\n`;
}
writeFileSync(join(mobile, 'css', 'icons.css'), css);
copyFileSync(join(root, 'src', 'assets', 'icons', 'LICENSE'), join(mobile, 'icons', 'LICENSE'));
copyFileSync(join(root, 'src', 'assets', 'icon.svg'), join(mobile, 'icon.svg'));
console.log(`Copied ${ICONS.length * 2} icons and the app icon into mobile/.`);

// --- Service worker: the list of app files to save for offline, and a fingerprint ---------
// Any change to any app file changes the fingerprint, which makes phones install the
// new service worker (and with it the new files) on their next launch.
const skip = new Set(['sw.js', '_headers', 'index.html']); // index.html is saved as "/"
const files = walk(mobile).filter((f) => !skip.has(f)).sort();
const hash = createHash('sha256');
for (const f of ['index.html', ...files]) hash.update(f).update(readFileSync(join(mobile, f)));
const version = hash.digest('hex').slice(0, 12);
const swPath = join(mobile, 'sw.js');
// Top-level pages are served at clean addresses (/privacy, not /privacy.html, which redirects).
const served = (f) => (/^[^/]+\.html$/.test(f) ? `/${f.slice(0, -'.html'.length)}` : `/${f}`);
const generated = `// BEGIN GENERATED (worker/scripts/build-mobile-assets.mjs)\n`
  + `const VERSION = '${version}';\n`
  + `const SHELL_FILES = ${JSON.stringify(['/', ...files.map(served)], null, 2)};\n`
  + `// END GENERATED`;
const sw = readFileSync(swPath, 'utf8').replace(/\/\/ BEGIN GENERATED[\s\S]*?\/\/ END GENERATED/, generated);
writeFileSync(swPath, sw);
console.log(`Service worker: ${files.length + 1} files, version ${version}.`);

function walk(dir, prefix = '') {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory()
    ? walk(join(dir, d.name), `${prefix}${d.name}/`)
    : [`${prefix}${d.name}`]));
}
